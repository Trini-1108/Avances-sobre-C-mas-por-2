// Definición de la función para calcular el área del círculo
double areaCirculo(double radio) {
    return 3.1416 * radio * radio;  // Fórmula del área de un círculo: π * radio²
}

// Definición de la función para calcular el área del rectángulo
double areaRectangulo(double largo, double ancho) {
    return largo * ancho;  // Fórmula del área de un rectángulo: largo * ancho
}

